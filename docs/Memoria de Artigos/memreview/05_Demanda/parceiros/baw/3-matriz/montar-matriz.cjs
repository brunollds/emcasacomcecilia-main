const esc = (v) => (/[",\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v);

// Uma linha cita outra por {{chave}}; o id sai da posição, então reordenar não quebra as citações.
const idDaChave = new Map();
LINHAS.forEach((l, i) => {
  if (!l.chave || idDaChave.has(l.chave)) throw new Error(`chave ausente ou repetida: ${l.chave}`);
  idDaChave.set(l.chave, `op-baw-${pad(i + 1)}`);
});
const resolver = (texto, onde) =>
  texto.replace(/\{\{([a-z0-9-]+)\}\}/g, (_, chave) => {
    if (!idDaChave.has(chave)) throw new Error(`${onde}: cita {{${chave}}}, que não existe`);
    return idDaChave.get(chave);
  });

const linhasCsv = LINHAS.map((l, i) => {
  const id = `op-baw-${pad(i + 1)}`;
  for (const campo of ['lacuna', 'justificativa', 'dependencias', 'notas']) l[campo] = resolver(l[campo], id);
  const linha = {
    oportunidade_id: id,
    parceiros: 'baw',
    entidades: l.entidades,
    intencao: l.intencao,
    perguntas: l.perguntas,
    pais: 'BR',
    idioma: 'pt-BR',
    sinais_ref: l.sinais,
    nossos_dados_ref: l.nossos,
    comercial_ref: l.comercial,
    cobertura_ref: l.cobertura,
    evidencias_principais: l.principais.join('|'),
    lacuna: l.lacuna,
    acao: l.acao,
    prioridade: l.prioridade,
    justificativa_prioridade: l.justificativa,
    confianca: l.confianca,
    dependencias: l.dependencias,
    estado_revisao: l.estado || 'em-revisao',
    notas: l.notas,
  };
  for (const c of CABECALHO) {
    if (linha[c] === undefined || String(linha[c]).trim() === '') throw new Error(`${id}: ${c} vazio`);
  }
  return CABECALHO.map((c) => esc(String(linha[c]))).join(',');
});

fs.writeFileSync(path.join(AQUI, 'matriz.csv'), `${CABECALHO.join(',')}\n${linhasCsv.join('\n')}\n`);

